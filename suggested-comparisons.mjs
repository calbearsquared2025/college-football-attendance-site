export function suggestedComparisonsFor(schoolId, schools, max = 3) {
  const byId = new Map(schools.map(school => [Number(school.school_id), school]));
  const byName = new Map(schools.map(school => [school.school_name, school]));
  const selected = byId.get(Number(schoolId));
  if (!selected) return [];
  return (SUGGESTED_SCHOOL_NAMES[selected.school_name] ?? [])
    .map(name => byName.get(name))
    .filter(school => school && Number(school.school_id) !== Number(schoolId))
    .slice(0, max);
}
